def build_qa_rich_message() -> dict:
    """Generate one RTL Rich Message with 23 independent, collapsed accordions."""
    parts = [
        "<h1>❓ سؤالات متداول ارسال بار | Advertio</h1>",
        "<p>موضوع موردنظر را انتخاب کنید و برای مشاهده پاسخ، روی هر سؤال بزنید.</p>",
    ]
    for section_title, questions in FAQ_SECTIONS:
        parts.append(f"<h2>{escape(section_title)}</h2>")
        for number, (question, answer_html) in enumerate(questions, start=1):
            # Numbering restarts per section; the questions remain independently collapsible.
            parts.append(
                "<details><summary>"
                + escape(f"{number}. {question}")
                + "</summary>"
                + answer_html
                + "</details>"
            )
    parts.append(
        "<tg-button-row>"
        '<tg-button type="url" style="primary" url="https://t.me/advertio_support">'
        "💬 پشتیبانی Advertio</tg-button>"
        '<tg-button type="url" url="https://t.me/advertio_bot">'
        "📝 ثبت آگهی</tg-button>"
        "</tg-button-row>"
    )
    parts.append("<p><i>Advertio | ارتباطی فراتر از مرزها</i></p>")
    return {"html": "\n".join(parts), "is_rtl": True, "skip_entity_detection": True}
